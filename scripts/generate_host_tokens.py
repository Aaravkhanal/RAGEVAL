"""Write distinct public/admin tokens into the gitignored .env. Never prints values."""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ENV_PATH = Path(os.environ.get("RAGEVAL_ENV_FILE") or REPO / ".env")

KEEP_KEYS = (
    "NVIDIA_API_KEY",
    "OPENAI_API_KEY",
    "RAGEVAL_API_KEY",
    "RAGEVAL_RUNS_DIR",
    "RAGEVAL_DATA_DIR",
    "RAGEVAL_INCLUDE_SNAPSHOTS",
    "RAGEVAL_CORS_ORIGINS",
    "RAGEVAL_ALLOWED_HOSTS",
    "RAGEVAL_RATE_LIMIT_PER_MINUTE",
    "RAGEVAL_READ_RATE_LIMIT_PER_MINUTE",
    "RAGEVAL_REQUIRE_AUTH",
    "RAGEVAL_PUBLIC_TOKEN",
    "RAGEVAL_ADMIN_TOKEN",
    "RAGEVAL_ENABLE_HTTP_NLI",
    "RAGEVAL_DOMAIN",
)


def _parse(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip("'").strip('"')
    return values


def write_env(
    path: Path = ENV_PATH,
    *,
    rotate_host_tokens: bool = True,
    clear_nvidia_key: bool = False,
) -> Path:
    existing = _parse(path.read_text(encoding="utf-8")) if path.exists() else {}
    if rotate_host_tokens or not existing.get("RAGEVAL_PUBLIC_TOKEN"):
        existing["RAGEVAL_PUBLIC_TOKEN"] = secrets.token_urlsafe(48)
    if rotate_host_tokens or not existing.get("RAGEVAL_ADMIN_TOKEN"):
        existing["RAGEVAL_ADMIN_TOKEN"] = secrets.token_urlsafe(48)
    if existing.get("RAGEVAL_PUBLIC_TOKEN") == existing.get("RAGEVAL_ADMIN_TOKEN"):
        existing["RAGEVAL_ADMIN_TOKEN"] = secrets.token_urlsafe(48)
    existing["RAGEVAL_REQUIRE_AUTH"] = "1"
    existing.setdefault("RAGEVAL_RATE_LIMIT_PER_MINUTE", "60")
    existing.setdefault("RAGEVAL_READ_RATE_LIMIT_PER_MINUTE", "120")
    existing.setdefault("RAGEVAL_ENABLE_HTTP_NLI", "0")
    existing.setdefault("RAGEVAL_DOMAIN", "localhost")
    existing.setdefault("RAGEVAL_CORS_ORIGINS", "http://127.0.0.1:8000,http://localhost:8000,https://localhost")
    existing.setdefault("RAGEVAL_ALLOWED_HOSTS", "localhost,127.0.0.1")
    if clear_nvidia_key:
        existing["NVIDIA_API_KEY"] = ""
    lines = [
        "# Gitignored. Generated by scripts/generate_host_tokens.py.",
        "# CLI loads this file. Docker Compose reads it if present.",
        "# Revoke any NVIDIA key that was pasted in chat at https://build.nvidia.com/",
        "",
    ]
    for key in KEEP_KEYS:
        if key in existing:
            lines.append(f"{key}={existing[key]}")
    for key, value in existing.items():
        if key not in KEEP_KEYS:
            lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(path, 0o600)
    return path


if __name__ == "__main__":
    write_env(clear_nvidia_key="--clear-nvidia" in sys.argv)
    print(f"Wrote host tokens to {ENV_PATH} (mode 0600; values not printed)")
